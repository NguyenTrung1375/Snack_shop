// Helper functions
export const getComboById = (id) => {
  return SNACK_COMBOS.find((c) => c.id === id) || SNACK_COMBOS[0];
};

export const getCombosByCategory = (catKey) => {
  if (!catKey || catKey === 'all') return SNACK_COMBOS;
  return SNACK_COMBOS.filter((c) => c.category === catKey);
};

export const formatVnd = (amount) => {
  const n = Number(amount) || 0;
  return n.toLocaleString('vi-VN') + ' đ';
};

